const AssistantMessage: FC = () => {
  const {
    ToolFallback: ToolFallbackComponent = ToolFallback,
    ToolGroup,
    ReasoningGroup,
  } = useContext(ThreadComponentsContext);



  return (
    <MessagePrimitive.Root
      data-slot="aui_assistant-message-root"
      data-role="assistant"
      className="fade-in slide-in-from-bottom-1 animate-in relative flex items-start gap-3 px-2 duration-150"
    >
      <AssistantAvatar />
      <div
        data-slot="aui_assistant-message-content"
        // [contain-intrinsic-size:auto_24px] fixes issue #4104, don't change without checking for regressions
        className="min-w-0 flex-1 text-foreground leading-relaxed wrap-break-word [contain-intrinsic-size:auto_24px] [content-visibility:auto]"
      >
        {useAuiState((s) => s.message.status?.type === "running" && s.message.parts.length === 0) && (
          <div className="mb-2 flex max-w-[70%] flex-col gap-2.5 animate-pulse">
            <div className="h-5 w-full rounded-full bg-muted" />
            <div className="h-5 w-3/4 rounded-full bg-muted/70" />
          </div>
        )}
        <MessagePrimitive.GroupedParts
          groupBy={groupPartByType({
            reasoning: ["group-chainOfThought", "group-reasoning"],
            "tool-call": ["group-chainOfThought", "group-tool"],
            "standalone-tool-call": [],
          })}
        >
          {({ part, children }) => {
            switch (part.type) {
              case "group-chainOfThought": {
                const running = part.status.type === "running";
                return (
                  <ChainOfThought active={running}>
                    {children}
                  </ChainOfThought>
                );
              }
              case "group-tool":
                if (ToolGroup) {
                  return <ToolGroup group={part}>{children}</ToolGroup>;
                }
                return (
                  <ToolGroupRoot variant="ghost" className="mb-3">
                    <ToolGroupTrigger
                      count={part.indices.length}
                      active={part.status.type === "running"}
                    />
                    <ToolGroupContent>{children}</ToolGroupContent>
                  </ToolGroupRoot>
                );
              case "group-reasoning": {
                if (ReasoningGroup) {
                  return (
                    <ReasoningGroup group={part}>{children}</ReasoningGroup>
                  );
                }
                const running = part.status.type === "running";
                return (
                  <ReasoningRoot>
                    <ReasoningTrigger active={running} />
                    <ReasoningContent aria-busy={running}>
                      <ReasoningText>{children}</ReasoningText>
                    </ReasoningContent>
                  </ReasoningRoot>
                );
              }
              case "text":
                return <FelloText />;
              case "reasoning":
                return <Reasoning {...part} />;
              case "tool-call":
                return part.toolUI ?? <ToolFallbackComponent {...part} />;
              case "data":
                return part.dataRendererUI;
              case "indicator":
                return null;
              default:
                return null;
            }
          }}
        </MessagePrimitive.GroupedParts>
        <MessageError />
        <div
          data-slot="aui_assistant-message-footer"
          className="mt-2 flex items-center gap-4"
        >
          <BranchPicker />
          {/* Action Bar Buttons */}
          <ActionBarPrimitive.Root hideWhenRunning autohide="not-last" className="flex items-center gap-2">
            <ActionBarPrimitive.Copy asChild>
              <TooltipIconButton tooltip="Copy" className="aui-assistant-copy">
                <CopyIcon className="size-4" />
              </TooltipIconButton>
            </ActionBarPrimitive.Copy>
            <ActionBarPrimitive.Reload asChild>
              <TooltipIconButton tooltip="Regenerate" className="aui-assistant-reload">
                <RefreshCwIcon className="size-4" />
              </TooltipIconButton>
            </ActionBarPrimitive.Reload>
            <ActionBarMorePrimitive.Root>
              <ActionBarMorePrimitive.Trigger asChild>
                <TooltipIconButton tooltip="More" className="aui-assistant-more">
                  <MoreHorizontalIcon className="size-4" />
                </TooltipIconButton>
              </ActionBarMorePrimitive.Trigger>
              <ActionBarMorePrimitive.Content
                side="bottom"
                align="start"
                sideOffset={6}
                className="aui-action-bar-more-content bg-popover/95 text-popover-foreground z-50 min-w-[8rem] overflow-hidden rounded-xl border p-1.5 shadow-lg backdrop-blur-sm"
              >
                <ActionBarPrimitive.ExportMarkdown asChild>
                  <ActionBarMorePrimitive.Item className="aui-action-bar-more-item hover:bg-accent hover:text-accent-foreground focus:bg-accent focus:text-accent-foreground flex cursor-pointer items-center gap-2 rounded-lg px-2.5 py-1.5 text-sm outline-none select-none">
                    <DownloadIcon className="size-4" />
                    Export as Markdown
                  </ActionBarMorePrimitive.Item>
                </ActionBarPrimitive.ExportMarkdown>
              </ActionBarMorePrimitive.Content>
            </ActionBarMorePrimitive.Root>
          </ActionBarPrimitive.Root>
        </div>
      </div>
    </MessagePrimitive.Root>
  );
};

